import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';

export interface PDFStudentInfo {
  name: string;
  admissionNumber: string;
  program: string;
  department?: string;
  school?: string;
  yearOfStudy: number;
  semesterNumber: number;
  status?: string;
}

export interface PDFCourseGrade {
  courseCode: string;
  courseTitle: string;
  creditHours: number;
  catScore: number;
  examScore: number;
  totalScore: number;
  letterGrade: string;
  gradePoint: number;
}

export interface PDFSemesterResult {
  semesterLabel: string;
  academicYear: string;
  courses: PDFCourseGrade[];
  gpa: number;
  creditsEarned: number;
}

export interface PDFTransaction {
  date: string;
  reference: string;
  description: string;
  method: string;
  amount: number;
  status: string;
}

const UNIVERSITY_HEADER = {
  name: 'ZETECH UNIVERSITY',
  motto: 'Invent Your Future',
  address: 'P.O. Box 2768 - 00200, Nairobi, Kenya',
  contact: 'Tel: +254 719 034 500 | Email: info@zetech.ac.ke | Web: www.zetech.ac.ke',
};

// Colors (Oxford Navy & University Gold)
const NAVY = [15, 23, 42]; // #0f172a
const GOLD = [217, 119, 6]; // #d97706
const SLATE = [100, 116, 139]; // #64748b

/**
 * Adds University Header & Crest Banner
 */
function addHeader(doc: jsPDF, title: string) {
  // Top Banner
  doc.setFillColor(NAVY[0], NAVY[1], NAVY[2]);
  doc.rect(0, 0, 210, 28, 'F');

  // Gold accent bar
  doc.setFillColor(GOLD[0], GOLD[1], GOLD[2]);
  doc.rect(0, 28, 210, 2, 'F');

  // Title text
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.text(UNIVERSITY_HEADER.name, 105, 12, { align: 'center' });

  doc.setFont('helvetica', 'italic');
  doc.setFontSize(8);
  doc.text(`"${UNIVERSITY_HEADER.motto}"`, 105, 17, { align: 'center' });

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7);
  doc.text(`${UNIVERSITY_HEADER.address} | ${UNIVERSITY_HEADER.contact}`, 105, 23, { align: 'center' });

  // Document Title Banner
  doc.setTextColor(NAVY[0], NAVY[1], NAVY[2]);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.text(title.toUpperCase(), 105, 38, { align: 'center' });

  // Thin separator under title
  doc.setDrawColor(226, 232, 240);
  doc.setLineWidth(0.5);
  doc.line(14, 42, 196, 42);
}

/**
 * Adds Footer with Date and Page Info
 */
function addFooter(doc: jsPDF, pageNumber: number, totalPages: number) {
  const pageHeight = doc.internal.pageSize.height || 297;
  doc.setDrawColor(226, 232, 240);
  doc.line(14, pageHeight - 15, 196, pageHeight - 15);

  doc.setFont('helvetica', 'italic');
  doc.setFontSize(7);
  doc.setTextColor(SLATE[0], SLATE[1], SLATE[2]);
  const dateStr = new Date().toLocaleString('en-KE', { timeZone: 'Africa/Nairobi' });
  doc.text(`Generated by UAMS Enterprise Core on ${dateStr} EAT • Official Valid Document`, 14, pageHeight - 10);
  doc.text(`Page ${pageNumber} of ${totalPages}`, 196, pageHeight - 10, { align: 'right' });
}

/**
 * 1. Official Academic Transcript PDF
 */
export function generateTranscriptPDF(data: {
  student: PDFStudentInfo;
  semesterResults: PDFSemesterResult[];
  cumulativeGpa: number;
  totalCredits: number;
  academicStanding: string;
}) {
  const doc = new jsPDF('p', 'mm', 'a4');
  addHeader(doc, 'OFFICIAL ACADEMIC TRANSCRIPT');

  // Student Details Box
  doc.setFillColor(248, 250, 252);
  doc.roundedRect(14, 46, 182, 32, 2, 2, 'F');
  doc.setDrawColor(226, 232, 240);
  doc.roundedRect(14, 46, 182, 32, 2, 2, 'S');

  doc.setFontSize(9);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(NAVY[0], NAVY[1], NAVY[2]);

  doc.text('Student Name:', 18, 53);
  doc.setFont('helvetica', 'normal');
  doc.text(data.student.name, 50, 53);

  doc.setFont('helvetica', 'bold');
  doc.text('Admission No:', 120, 53);
  doc.setFont('helvetica', 'normal');
  doc.text(data.student.admissionNumber, 150, 53);

  doc.setFont('helvetica', 'bold');
  doc.text('Program:', 18, 60);
  doc.setFont('helvetica', 'normal');
  doc.text(data.student.program, 50, 60);

  doc.setFont('helvetica', 'bold');
  doc.text('Current Level:', 120, 60);
  doc.setFont('helvetica', 'normal');
  doc.text(`Year ${data.student.yearOfStudy}, Sem ${data.student.semesterNumber}`, 150, 60);

  doc.setFont('helvetica', 'bold');
  doc.text('Cumulative GPA:', 18, 67);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(GOLD[0], GOLD[1], GOLD[2]);
  doc.text(`${data.cumulativeGpa.toFixed(2)} / 4.00`, 50, 67);

  doc.setTextColor(NAVY[0], NAVY[1], NAVY[2]);
  doc.setFont('helvetica', 'bold');
  doc.text('Standing / Honors:', 120, 67);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(16, 149, 100);
  doc.text(data.academicStanding, 150, 67);

  let currentY = 84;

  data.semesterResults.forEach((sem) => {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10);
    doc.setTextColor(NAVY[0], NAVY[1], NAVY[2]);
    doc.text(`${sem.semesterLabel.toUpperCase()} — ${sem.academicYear}`, 14, currentY);

    const tableBody = sem.courses.map((c) => [
      c.courseCode,
      c.courseTitle,
      c.creditHours.toString(),
      c.catScore.toString(),
      c.examScore.toString(),
      c.totalScore.toString(),
      c.letterGrade,
      c.gradePoint.toFixed(1),
    ]);

    autoTable(doc, {
      startY: currentY + 3,
      head: [['Code', 'Course Title', 'Credits', 'CAT (30)', 'Exam (70)', 'Total', 'Grade', 'Points']],
      body: tableBody,
      theme: 'grid',
      headStyles: {
        fillColor: [15, 23, 42],
        textColor: [255, 255, 255],
        fontSize: 8,
        fontStyle: 'bold',
      },
      styles: {
        fontSize: 8,
        cellPadding: 2,
        textColor: [30, 41, 59],
      },
      columnStyles: {
        0: { cellWidth: 24, fontStyle: 'bold' },
        1: { cellWidth: 68 },
        2: { cellWidth: 16, halign: 'center' },
        3: { cellWidth: 16, halign: 'center' },
        4: { cellWidth: 16, halign: 'center' },
        5: { cellWidth: 14, halign: 'center', fontStyle: 'bold' },
        6: { cellWidth: 14, halign: 'center', fontStyle: 'bold' },
        7: { cellWidth: 14, halign: 'center' },
      },
      margin: { left: 14, right: 14 },
    });

    const finalY = (doc as any).lastAutoTable.finalY || currentY + 40;

    // Semester summary line
    doc.setFontSize(8);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(NAVY[0], NAVY[1], NAVY[2]);
    doc.text(`Semester GPA: ${sem.gpa.toFixed(2)}  |  Credits Earned: ${sem.creditsEarned}`, 14, finalY + 5);

    currentY = finalY + 12;
  });

  // Signatures Section
  const pageHeight = doc.internal.pageSize.height || 297;
  const sigY = Math.min(currentY + 10, pageHeight - 40);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(NAVY[0], NAVY[1], NAVY[2]);

  doc.line(18, sigY + 12, 70, sigY + 12);
  doc.text('Registrar (Academic Affairs)', 18, sigY + 16);

  doc.line(140, sigY + 12, 192, sigY + 12);
  doc.text('Dean of Faculty / School', 140, sigY + 16);

  // University Seal Stamp watermark placeholder
  doc.setDrawColor(GOLD[0], GOLD[1], GOLD[2]);
  doc.setLineWidth(1);
  doc.circle(105, sigY + 10, 10, 'S');
  doc.setFontSize(6);
  doc.setTextColor(GOLD[0], GOLD[1], GOLD[2]);
  doc.text('OFFICIAL SEAL', 105, sigY + 11, { align: 'center' });

  addFooter(doc, 1, 1);
  return doc;
}

